package com.akilisha.oss.roya.plugins.email.providers;

/**
 * Email provider features.
 */
public enum EmailFeature {
    /**
     * Analytics and tracking (opens, clicks).
     */
    ANALYTICS,
    /**
     * Tags for categorization.
     */
    TAGS,
    /**
     * Webhooks for delivery events.
     */
    WEBHOOKS,
    /**
     * Template engine support.
     */
    TEMPLATES,
    /**
     * Scheduled sending.
     */
    SCHEDULING,
    /**
     * Batch sending.
     */
    BATCH
}

